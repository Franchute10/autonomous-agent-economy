let language = "es";
let latestReport = null;
const form = document.querySelector("#diagnosis-form");
const button = document.querySelector("#submit-button");
const feedback = document.querySelector("#feedback");
const reportPanel = document.querySelector("#report");
const fixPackCard = document.querySelector("#fix-pack-card");
const fixPackButton = document.querySelector("#fix-pack-button");
const fixPackStatus = document.querySelector("#fix-pack-status");
const fixPackIncluded = document.querySelector("#fix-pack-included");
const fixPackPages = document.querySelector("#fix-pack-pages");
let fixPackMarkdown = null;
let pendingTransactionId = null;
let paddleInitialized = false;

function localized(value) {
  if (value && typeof value === "object") return value[language] ?? value.es ?? "";
  return value ?? "";
}

function setLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const translated = copy[language][key];
    if (translated) element.innerHTML = translated;
  });
  document.querySelectorAll(".language-button").forEach((element) => {
    const active = element.dataset.language === language;
    element.classList.toggle("is-active", active);
    element.setAttribute("aria-pressed", String(active));
  });
  if (latestReport) renderReport(latestReport);
}

document.querySelectorAll(".language-button").forEach((element) => {
  element.addEventListener("click", () => setLanguage(element.dataset.language));
});

fixPackButton.addEventListener("click", async () => {
  if (fixPackMarkdown) {
    downloadFixPack(fixPackMarkdown);
    return;
  }
  if (pendingTransactionId) {
    await redeemFixPack(pendingTransactionId);
    return;
  }
  if (!latestReport?.fix_pack_available) return;
  fixPackButton.disabled = true;
  fixPackStatus.textContent = copy[language].fixPackPreparing;
  try {
    const response = await fetch("/api/fix-pack/checkout", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ url: latestReport.submitted_url, language })
    });
    const result = await response.json();
    const config = window.AEOS_PADDLE_CONFIG;
    if (!response.ok || !config?.enabled || result.price_id !== config.priceId) {
      throw new Error("checkout_failed");
    }
    if (!window.Paddle) throw new Error("paddle_unavailable");
    if (!paddleInitialized) {
      Paddle.Environment.set("sandbox");
      Paddle.Initialize({
        token: config.clientToken,
        eventCallback: handlePaddleEvent
      });
      paddleInitialized = true;
    }
    Paddle.Checkout.open({
      items: [{ priceId: result.price_id, quantity: 1 }],
      customData: result.custom_data,
      settings: {
        displayMode: "overlay",
        variant: "one-page",
        locale: language
      }
    });
  } catch {
    fixPackStatus.textContent = copy[language].fixPackCheckoutFailed;
    fixPackButton.disabled = !window.AEOS_PADDLE_CONFIG?.enabled;
  }
});

function handlePaddleEvent(event) {
  if (event.name === "checkout.completed") {
    const transactionId = event.data?.transaction_id;
    if (typeof transactionId === "string" && /^txn_[a-z0-9]{26}$/.test(transactionId)) {
      pendingTransactionId = transactionId;
      sessionStorage.setItem("aeos_fix_pack_transaction_id", transactionId);
      void redeemFixPack(transactionId);
    }
  } else if (event.name === "checkout.closed") {
    if (!pendingTransactionId && !fixPackMarkdown) {
      fixPackButton.disabled = !window.AEOS_PADDLE_CONFIG?.enabled;
      fixPackStatus.textContent = "";
    }
  } else if (
    event.name === "checkout.error" ||
    event.name === "checkout.payment.error" ||
    event.name === "checkout.payment.failed"
  ) {
    fixPackButton.disabled = !window.AEOS_PADDLE_CONFIG?.enabled;
    fixPackStatus.textContent = copy[language].fixPackCheckoutFailed;
  }
}

const storedTransactionId = sessionStorage.getItem("aeos_fix_pack_transaction_id");
if (storedTransactionId && /^txn_[a-z0-9]{26}$/.test(storedTransactionId)) {
  pendingTransactionId = storedTransactionId;
  fixPackCard.hidden = false;
  document.querySelector("#fix-pack-eyebrow").textContent = copy[language].fixPackEyebrow;
  document.querySelector("#fix-pack-title").textContent = "AEOS Fix Pack";
  document.querySelector("#fix-pack-description").textContent =
    copy[language].fixPackPaymentPending;
  fixPackIncluded.hidden = true;
  fixPackPages.hidden = true;
  fixPackButton.textContent = copy[language].fixPackCheckPayment;
  fixPackStatus.textContent = copy[language].fixPackPaymentPending;
  void redeemFixPack(storedTransactionId);
}

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  feedback.hidden = true;
  reportPanel.hidden = true;
  button.disabled = true;
  button.querySelector("[data-i18n]").textContent = copy[language].loading;

  try {
    const response = await fetch("/api/diagnose", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        url: normalizeUrl(document.querySelector("#site-url").value),
        language
      })
    });
    const result = await response.json();
    if (!response.ok) {
      showError(result.error, response.headers.get("Retry-After"));
      return;
    }
    latestReport = result;
    renderReport(result);
    reportPanel.hidden = false;
    reportPanel.scrollIntoView({ behavior: "smooth", block: "start" });
  } catch {
    showError("unknown");
  } finally {
    button.disabled = false;
    button.querySelector("[data-i18n]").textContent = copy[language].submit;
  }
});

function showError(code, retryAfter) {
  const message = copy[language].errors[code] || copy[language].errors.unknown;
  feedback.textContent = message;
  if (code === "rate_limit" && retryAfter) {
    const seconds = Number(retryAfter);
    if (Number.isFinite(seconds) && seconds > 0 && seconds <= 3600) {
      feedback.textContent += ` (${seconds}s)`;
    }
  }
  feedback.classList.add("is-error");
  feedback.hidden = false;
  feedback.scrollIntoView({ behavior: "smooth", block: "center" });
}

function renderReport(data) {
  const reportCopy = copy[language];
  document.querySelector("#summary").textContent = localized(data.summary);
  const chip = document.querySelector("#platform-chip");
  chip.textContent = data.platform.replaceAll("_", " ");
  document.querySelector("#confirmed-count").textContent = data.confirmed_findings.length;
  document.querySelector("#pending-count").textContent = data.pending_verifications.length;
  fillList("confirmed-list", "confirmed-empty", data.confirmed_findings, true);
  fillList("pending-list", "pending-empty", data.pending_verifications, false);
  document.querySelector("#limits").textContent = localized(data.limits);
  const offer = data.fix_pack_offer;
  fixPackCard.hidden = data.fix_pack_available !== true || !offer;
  if (fixPackCard.hidden) {
    if (!pendingTransactionId && !fixPackMarkdown) fixPackStatus.textContent = "";
  } else {
    renderFixPackOffer(offer);
  }

  const access = document.querySelector("#access-request");
  if (data.access_request) {
    access.replaceChildren();
    const title = document.createElement("strong");
    title.textContent = reportCopy.accessLabel;
    const text = document.createElement("p");
    text.textContent = localized(data.access_request);
    access.append(title, text);
    access.hidden = false;
  } else {
    access.hidden = true;
  }
}

function renderFixPackOffer(offer) {
  document.querySelector("#fix-pack-eyebrow").textContent = copy[language].fixPackEyebrow;
  document.querySelector("#fix-pack-title").textContent = offer.product;
  document.querySelector("#fix-pack-price").textContent =
    offer.currency + " " + (offer.amount_minor / 100).toFixed(2) +
    " · " + (language === "es" ? "pago único" : "one-time");
  document.querySelector("#fix-pack-description").textContent =
    copy[language].fixPackDescription;

  fixPackIncluded.replaceChildren();
  appendFixPackList(
    fixPackIncluded,
    copy[language].fixPackContentsTitle,
    [
      copy[language].fixPackPerPage.replace(
        "{count}",
        String(offer.implementation_step_count)
      )
    ]
  );
  appendFixPackList(
    fixPackIncluded,
    copy[language].fixPackTemplatesTitle,
    [offer.title_template, offer.description_template]
  );
  appendFixPackList(
    fixPackIncluded,
    copy[language].fixPackImplementationTitle,
    offer.implementation_steps
  );
  appendFixPackList(
    fixPackIncluded,
    language === "es" ? "Qué no incluye" : "Not included",
    [copy[language].fixPackAccessRequired]
  );
  appendFixPackList(
    fixPackIncluded,
    copy[language].fixPackQualityChecks.replace(
      "{count}",
      String(offer.quality_checks.length)
    ),
    offer.quality_checks
  );
  appendFixPackList(
    fixPackIncluded,
    copy[language].fixPackLimitations.replace(
      "{count}",
      String(offer.limitations.length)
    ),
    offer.limitations
  );
  fixPackIncluded.hidden = false;

  fixPackPages.replaceChildren();
  const pageHeading = document.createElement("h4");
  pageHeading.textContent = copy[language].fixPackPagesTitle;
  const pageCount = document.createElement("p");
  pageCount.className = "fix-pack-page-count";
  pageCount.textContent = copy[language].fixPackPageCount.replace(
    "{count}",
    String(offer.pages.length)
  );
  const pageList = document.createElement("ul");
  for (const page of offer.pages) {
    const item = document.createElement("li");
    const url = document.createElement("strong");
    url.textContent = page.url;
    const finding = document.createElement("span");
    finding.textContent = " — " + page.finding;
    item.append(url, finding);
    pageList.append(item);
  }
  fixPackPages.append(pageHeading, pageCount, pageList);
  fixPackPages.hidden = false;

  fixPackButton.textContent = fixPackMarkdown
    ? copy[language].fixPackDownload
    : pendingTransactionId
      ? copy[language].fixPackCheckPayment
      : copy[language].fixPackBuy;
  fixPackButton.disabled =
    !window.AEOS_PADDLE_CONFIG?.enabled && !fixPackMarkdown;
  fixPackStatus.textContent =
    !window.AEOS_PADDLE_CONFIG?.enabled && !fixPackMarkdown
      ? copy[language].fixPackCheckoutDisabled
      : "";
}

function appendFixPackList(parent, headingText, entries) {
  const section = document.createElement("section");
  const heading = document.createElement("h4");
  heading.textContent = headingText;
  const list = document.createElement("ul");
  for (const entry of entries) {
    const item = document.createElement("li");
    item.textContent = entry;
    list.append(item);
  }
  section.append(heading, list);
  parent.append(section);
}

function fillList(containerId, emptyId, entries, confirmed) {
  const container = document.getElementById(containerId);
  container.replaceChildren();
  document.getElementById(emptyId).hidden = entries.length > 0;
  for (const item of entries) container.append(createFindingCard(item, confirmed));
}

function createFindingCard(item, confirmed) {
  const card = document.createElement("article");
  card.className = "finding-card";
  const top = document.createElement("div");
  top.className = "finding-card-top";
  const number = document.createElement("span");
  number.className = "finding-number";
  number.textContent = String(item.priority).padStart(2, "0");
  const title = document.createElement("h4");
  title.textContent = localized(item.title);
  top.append(number, title);
  card.append(top);

  addLabeledText(card, copy[language].evidenceLabel, localized(item.evidence), "evidence-block");
  if (item.sources?.length) {
    const links = document.createElement("div");
    links.className = "source-links";
    for (const source of item.sources) {
      const link = document.createElement("a");
      link.textContent = copy[language].sourceLabel;
      const parsed = safeLink(source.url);
      if (parsed) {
        link.href = parsed;
        link.target = "_blank";
        link.rel = "noopener noreferrer";
      }
      const excerpt = document.createElement("span");
      excerpt.textContent = localized(source.evidence);
      links.append(link, excerpt);
    }
    card.append(links);
  }
  if (confirmed) {
    addLabeledText(card, copy[language].actionLabel, localized(item.action), "action-block");
    addPrompt(card, localized(item.correction_prompt));
  } else {
    addLabeledText(card, copy[language].nextLabel, localized(item.next_step), "action-block");
  }
  return card;
}

function addLabeledText(parent, labelText, content, className) {
  const wrapper = document.createElement("div");
  wrapper.className = className;
  const label = document.createElement("span");
  label.className = "micro-label";
  label.textContent = labelText;
  const text = document.createElement("p");
  text.textContent = content;
  wrapper.append(label, text);
  parent.append(wrapper);
}

function addPrompt(parent, promptText) {
  if (!promptText) return;
  const wrapper = document.createElement("div");
  wrapper.className = "prompt-block";
  const head = document.createElement("div");
  head.className = "prompt-head";
  const label = document.createElement("span");
  label.className = "micro-label";
  label.textContent = copy[language].promptLabel;
  const copyButton = document.createElement("button");
  copyButton.type = "button";
  copyButton.className = "copy-button";
  copyButton.textContent = copy[language].copyPrompt;
  const prompt = document.createElement("p");
  prompt.textContent = promptText;
  copyButton.addEventListener("click", async () => {
    try {
      await navigator.clipboard.writeText(promptText);
      copyButton.textContent = copy[language].copied;
      window.setTimeout(() => { copyButton.textContent = copy[language].copyPrompt; }, 1400);
    } catch {
      copyButton.textContent = promptText;
    }
  });
  head.append(label, copyButton);
  wrapper.append(head, prompt);
  parent.append(wrapper);
}

function safeLink(value) {
  try {
    const url = new URL(value);
    if (url.protocol === "https:" || url.protocol === "http:") return url.href;
  } catch {
    return null;
  }
  return null;
}

function normalizeUrl(value) {
  const trimmed = value.trim();
  if (/^[a-z][a-z0-9+.-]*:/i.test(trimmed)) return trimmed;
  return `https://${trimmed}`;
}

async function redeemFixPack(transactionId) {
  fixPackCard.hidden = false;
  fixPackButton.disabled = true;
  fixPackStatus.textContent = copy[language].fixPackPaymentPending;
  try {
    for (let attempt = 0; attempt < 10; attempt += 1) {
      const response = await fetch("/api/fix-pack/redeem", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ transaction_id: transactionId })
      });
      if (response.status === 202) {
        if (attempt < 9) {
          await new Promise((resolve) => window.setTimeout(resolve, 1200));
          continue;
        }
        throw new Error("payment_pending");
      }
      const result = await response.json();
      if (response.status === 402) throw new Error("payment_invalid");
      if (!response.ok || typeof result.markdown !== "string") {
        throw new Error("payment_unavailable");
      }
      fixPackMarkdown = result.markdown;
      fixPackButton.disabled = false;
      fixPackButton.textContent = copy[language].fixPackDownload;
      fixPackStatus.textContent = copy[language].fixPackPaymentConfirmed;
      fixPackCard.scrollIntoView({ behavior: "smooth", block: "center" });
      return;
    }
  } catch (error) {
    fixPackStatus.textContent =
      error instanceof Error && error.message === "payment_invalid"
        ? copy[language].fixPackPaymentInvalid
        : copy[language].fixPackCheckoutFailed;
    fixPackButton.disabled = false;
    fixPackButton.textContent = copy[language].fixPackCheckPayment;
    fixPackCard.scrollIntoView({ behavior: "smooth", block: "center" });
  }
}

function downloadFixPack(markdown) {
  const blob = new Blob([markdown], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = "aeos-fix-pack.md";
  link.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 0);
}
